// Build-time: rasterise Natural Earth land (public domain, via the `world-atlas` npm package)
// into a tile land-mask using the Miller cylindrical projection, RLE + base64 encode it, and
// write src/js/01_mapdata.js.
// Usage: node tools/genmap.mjs <path-to-node_modules-containing-world-atlas-and-topojson-client>
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';

const nm = process.argv[2];
if (!nm) { console.error('pass node_modules dir'); process.exit(1); }
const require = createRequire(path.join(nm, 'x.js'));
const topo = require('topojson-client');
const land = require(path.join(nm, 'world-atlas/land-50m.json'));

const W = 2000;
const LAT_N = 80, LAT_S = -58;
const K = W / (2 * Math.PI);
const millerY = (latDeg) => 1.25 * Math.log(Math.tan(Math.PI / 4 + 0.4 * latDeg * Math.PI / 180));
const Y0 = millerY(LAT_N);
const H = Math.round((Y0 - millerY(LAT_S)) * K);
const px = (lon) => (lon + 180) / 360 * W;
const py = (lat) => (Y0 - millerY(Math.max(-85, Math.min(85, lat)))) * K;

const fc = topo.feature(land, land.objects.land);
const rings = [];
for (const f of (fc.features || [fc])) {
  const g = f.geometry;
  const polys = g.type === 'Polygon' ? [g.coordinates] : g.coordinates;
  for (const poly of polys) for (const ring of poly) rings.push(ring.map(([lo, la]) => [px(lo), py(la)]));
}
console.log('rings', rings.length, 'W', W, 'H', H);

// even-odd scanline fill, sampling at pixel centres
const mask = new Uint8Array(W * H);
const rowX = Array.from({ length: H }, () => []);
for (const r of rings) {
  for (let i = 0, n = r.length; i < n; i++) {
    const [x1, y1] = r[i], [x2, y2] = r[(i + 1) % n];
    if (y1 === y2) continue;
    const ymin = Math.min(y1, y2), ymax = Math.max(y1, y2);
    let ys = Math.ceil(ymin - 0.5), ye = Math.floor(ymax - 0.5);
    if (ys < 0) ys = 0; if (ye > H - 1) ye = H - 1;
    for (let y = ys; y <= ye; y++) {
      const cy = y + 0.5;
      if (cy < ymin || cy >= ymax) continue;
      rowX[y].push(x1 + (cy - y1) * (x2 - x1) / (y2 - y1));
    }
  }
}
for (let y = 0; y < H; y++) {
  const xs = rowX[y].sort((a, b) => a - b);
  for (let i = 0; i + 1 < xs.length; i += 2) {
    let a = Math.ceil(xs[i] - 0.5), b = Math.floor(xs[i + 1] - 0.5);
    if (a < 0) a = 0; if (b > W - 1) b = W - 1;
    for (let x = a; x <= b; x++) mask[y * W + x] ^= 1; // xor handles overlapping rings
  }
}
// remove single-pixel specks of water inside land and isolated 1-tile land specks
let landCount = 0;
for (let i = 0; i < W * H; i++) landCount += mask[i];
console.log('land tiles', landCount, (100 * landCount / (W * H)).toFixed(1) + '%');

// RLE: alternating runs starting with water; varint bytes
const bytes = [];
const pushVar = (v) => { while (v >= 128) { bytes.push((v & 127) | 128); v >>>= 7; } bytes.push(v); };
let cur = 0, run = 0;
for (let i = 0; i < W * H; i++) {
  if (mask[i] === cur) run++;
  else { pushVar(run); cur = mask[i]; run = 1; }
}
pushVar(run);
const b64 = Buffer.from(Uint8Array.from(bytes)).toString('base64');
const out = `/* generated by tools/genmap.mjs — Natural Earth 1:50m land (public domain), Miller projection */
(function(){ window.MP = window.MP || {}; MP.MAPDATA = { w:${W}, h:${H}, latN:${LAT_N}, latS:${LAT_S}, land:${landCount},
rle:"${b64}" }; })();
`;
fs.writeFileSync(new URL('../src/js/01_mapdata.js', import.meta.url), out);
console.log('wrote', out.length, 'bytes');
